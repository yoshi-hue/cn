"""Create submission figures from source and an actual JSONL trial log.

The script intentionally uses only the standard library. The timeline is
never simulated: it is a projection of run_start, detector_timing, alert, and
mitigation events present in the supplied raw log.
"""
import argparse
import json
from pathlib import Path


def svg_header(title, width=1200, height=700):
    return '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d"><title>%s</title>' % (width, height, width, height, title)


def architecture(path):
    s = [svg_header("Lantern architecture")]
    s += ['<rect width="100%" height="100%" fill="white"/>',
          '<style>text{font:16px sans-serif}.box{fill:#eef4ff;stroke:#244a86;stroke-width:2}.arrow{stroke:#333;stroke-width:2;marker-end:url(#a)}</style>',
          '<defs><marker id="a" markerWidth="8" markerHeight="8" refX="7" refY="3" orient="auto"><path d="M0,0 L8,3 L0,6 z" fill="#333"/></marker></defs>']
    boxes = [(60, 100, 170, 70, "Mininet hosts"), (280, 100, 190, 70, "OpenFlow switches"),
             (530, 100, 190, 70, "Ryu controller"), (790, 55, 220, 70, "Flow collector\n+windowing"),
             (790, 165, 220, 70, "Baseline\nthreshold rules"), (1030, 165, 120, 70, "Hybrid"),
             (1030, 55, 120, 70, "Graph\nclassifier"), (790, 300, 220, 70, "Alert manager\ncommon policy"),
             (1030, 300, 120, 70, "FlowMod +\nbarrier")]
    for x, y, w, h, label in boxes:
        s.append('<rect class="box" x="%d" y="%d" width="%d" height="%d" rx="8"/>' % (x, y, w, h))
        for i, line in enumerate(label.split("\n")):
            s.append('<text x="%d" y="%d" text-anchor="middle">%s</text>' % (x+w//2, y+30+i*20, line))
    arrows = [(230,135,280,135),(470,135,530,135),(720,135,790,90),(720,135,790,200),
              (1010,90,1030,90),(1010,200,1030,200),(1090,125,1090,165),
              (890,235,890,300),(1090,235,1090,300),(1010,335,1030,335)]
    for x1,y1,x2,y2 in arrows:
        s.append('<line class="arrow" x1="%d" y1="%d" x2="%d" y2="%d"/>' % (x1,y1,x2,y2))
    s.append('<text x="60" y="470">Both detectors consume the same closed Window object; mitigation is scored under one class-equivalent policy.</text></svg>')
    path.write_text("".join(s), encoding="utf-8")


def timeline(raw, path):
    events = [json.loads(line) for line in raw.read_text(encoding="utf-8").splitlines() if line.strip()]
    relevant = [e for e in events if e.get("kind") in {"run_start", "detector_timing", "alert", "mitigation_decided", "barrier_reply"}]
    if not relevant:
        raise RuntimeError("no timeline events in %s" % raw)
    end = max(float(e.get("t", 0)) for e in relevant) or 1.0
    width, left, right = 1200, 90, 1100
    s = [svg_header("Actual trial timeline", width, 420), '<rect width="100%" height="100%" fill="white"/>', '<style>text{font:14px sans-serif}.event{stroke:#244a86;stroke-width:3}</style>']
    s.append('<line x1="%d" y1="200" x2="%d" y2="200" stroke="#555"/>' % (left,right))
    colors = {"run_start":"#777", "detector_timing":"#2b6cb0", "alert":"#c53030", "mitigation_decided":"#dd6b20", "barrier_reply":"#2f855a"}
    for e in relevant:
        t = float(e.get("t", 0)); x = left + (right-left) * t / end
        kind = e["kind"]
        s.append('<line class="event" x1="%.1f" y1="175" x2="%.1f" y2="225" stroke="%s"/>' % (x,x,colors.get(kind,"#333")))
        s.append('<text x="%.1f" y="155" transform="rotate(-55 %.1f 155)">%s %.2fs</text>' % (x,x,kind,t))
    for t in (0, end/2, end):
        x = left + (right-left)*t/end
        s.append('<text x="%.1f" y="250" text-anchor="middle">%.1fs</text>' % (x,t))
    s.append('<text x="90" y="300">Source: %s</text>' % raw.name)
    s.append('<text x="90" y="330">Events are plotted from the trial JSONL; no timing values are generated by this script.</text></svg>')
    path.write_text("".join(s), encoding="utf-8")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--raw", type=Path, required=True)
    p.add_argument("--output", type=Path, default=Path("results/figs"))
    args = p.parse_args(); args.output.mkdir(parents=True, exist_ok=True)
    architecture(args.output / "architecture.svg")
    timeline(args.raw, args.output / "actual-trial-timeline.svg")


if __name__ == "__main__":
    main()
